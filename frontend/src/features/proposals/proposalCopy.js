export const getProposalCopy = (language) => PROPOSAL_COPY[language] || PROPOSAL_COPY.en;

export const PROPOSAL_VALIDITY_DAYS = 30;

const PROPOSAL_DATE_LOCALES = { en: "en-US", es: "es-CL", pt: "pt-BR" };

export function formatProposalDate(date, language) {
  const locale = PROPOSAL_DATE_LOCALES[language] || PROPOSAL_DATE_LOCALES.en;
  return new Intl.DateTimeFormat(locale, { day: "numeric", month: "long", year: "numeric" }).format(date);
}
